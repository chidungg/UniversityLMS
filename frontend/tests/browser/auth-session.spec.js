import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
async function login(page, role, password = 'Browser-test-2026') {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(`${role}@browser.test`)
  await page.getByLabel('Mật khẩu', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
}
test('real API: cookie session, RBAC, recovery, Admin reset, mandatory password change and logout', async ({ page, browser }) => {
  await page.goto('/admin/password-resets')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Email', { exact: true }).fill('student@browser.test')
  await page.getByLabel('Mật khẩu', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('không đúng')
  await expect(page).toHaveURL(/\/login$/)
  await page.setViewportSize({ width: 375, height: 812 })
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/a01-login-mobile.png', fullPage: true })
  await login(page, 'student')
  await expect(page).toHaveURL(/\/student\/courses$/)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Đăng xuất', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('lms_token'))).toBeNull()
  expect((await page.context().cookies()).find((cookie) => cookie.name === 'lms_session')?.httpOnly).toBe(true)
  await page.goto('/admin/password-resets')
  await expect(page).toHaveURL(/\/403$/)

  const guest = await browser.newContext()
  const recovery = await guest.newPage()
  await recovery.goto('http://127.0.0.1:4173/forgot-password')
  await recovery.getByLabel('Email', { exact: true }).fill('student@browser.test')
  await recovery.getByLabel('Ghi chú').fill('Please verify my identity in person.')
  await recovery.getByRole('button', { name: 'Gửi yêu cầu' }).click()
  await expect(recovery.getByRole('status')).toContainText('Đã tiếp nhận')

  const adminContext = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const admin = await adminContext.newPage()
  await admin.goto('http://127.0.0.1:4173/login')
  await admin.getByLabel('Email', { exact: true }).fill('administrator@browser.test')
  await admin.getByLabel('Mật khẩu', { exact: true }).fill('Browser-test-2026')
  await admin.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(admin).toHaveURL(/\/admin\/users$/)
  await admin.goto('http://127.0.0.1:4173/admin/password-resets')
  await admin.getByRole('button', { name: 'Xử lý', exact: true }).click()
  await admin.getByRole('checkbox').check()
  await admin.getByLabel('Mật khẩu tạm', { exact: true }).fill('Temporary-browser-2026')
  await admin.getByLabel('Xác nhận mật khẩu tạm', { exact: true }).fill('Temporary-browser-2026')
  await admin.getByLabel('Ghi chú xử lý').fill('Verified in person')
  await admin.getByRole('button', { name: 'Xác nhận đặt lại', exact: true }).click()
  await expect(admin.getByRole('status')).toContainText('Đã đặt lại mật khẩu')
  await admin.screenshot({ path: 'test-results/a01-admin-recovery.png', fullPage: true })
  await page.goto('/student/courses')
  await expect(page).toHaveURL(/\/login$/)
  await login(page, 'student', 'Temporary-browser-2026')
  await expect(page).toHaveURL(/\/change-password$/)
  await page.getByLabel('Mật khẩu hiện tại', { exact: true }).fill('Temporary-browser-2026')
  await page.getByLabel('Mật khẩu mới', { exact: true }).fill('Private-browser-2026')
  await page.getByLabel('Xác nhận mật khẩu mới', { exact: true }).fill('Private-browser-2026')
  await page.getByRole('button', { name: 'Lưu mật khẩu mới' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await login(page, 'student', 'Private-browser-2026')
  await expect(page).toHaveURL(/\/student\/courses$/)
  await page.goto('/student/assignments')
  await expect(page).toHaveURL(/\/student\/assignments$/)
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goBack()
  await expect(page).toHaveURL(/\/login$/)
  await login(page, 'instructor')
  await expect(page).toHaveURL(/\/instructor\/classes$/)
  await expect(page.getByRole('heading', { name: 'Lớp tôi dạy' })).toBeVisible()
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await guest.close(); await adminContext.close()
})
