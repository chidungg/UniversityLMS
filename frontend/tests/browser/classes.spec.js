import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const classKey = 'university-lms.class-preview.v1'
const courseKey = 'university-lms.course-preview.v1'
const rowFor = (page, code) => page.locator('tbody tr').filter({ has: page.getByRole('button', { name: `View ${code}`, exact: true }) })
async function openClasses(page) { await page.goto('/admin/classes'); await expect(page.getByRole('table')).toBeVisible() }
async function addClass(page, code = 'SE104-03', courseId = 'SE104') {
  await page.getByRole('button', { name: 'Add class', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Class code', { exact: false }).fill(code)
  await dialog.getByLabel('Course', { exact: false }).selectOption(courseId)
  await dialog.getByRole('button', { name: 'Add class', exact: true }).click()
  await expect(dialog).toHaveCount(0)
}

for (const width of [1024, 1440, 1920]) {
  test(`class directory desktop ${width}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    await openClasses(page)
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await expect(page.getByText(/semester|academic year/i)).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath(`classes-${width}.png`), fullPage: true })
  })
}

