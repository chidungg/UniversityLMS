test('add required/duplicate validation, inactive course exclusion, persistence', async ({ page }, testInfo) => {
  await openClasses(page)
  await page.getByRole('button', { name: 'Add class', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('Class code', { exact: false })).toBeFocused()
  await dialog.getByRole('button', { name: 'Add class', exact: true }).click()
  await expect(dialog.locator('.user-error-summary')).toBeFocused()
  await expect(dialog.locator('#class-code-error')).toHaveText('Enter a class code.')
  await expect(dialog.locator('#class-courseId-error')).toHaveText('Select a course.')
  await dialog.getByLabel('Class code', { exact: false }).fill(' se104-01 ')
  await dialog.getByLabel('Course', { exact: false }).selectOption('SE104')
  await expect(dialog.locator('option[value="NET301"]')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Add class', exact: true }).click()
  await expect(dialog.locator('#class-code-error')).toContainText('already in use')
  await dialog.getByLabel('Class code', { exact: false }).fill('se104-03')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('add-class.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Add class', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Saving…' })).toBeDisabled()
  await expect(dialog).toHaveCount(0)
  await expect(rowFor(page, 'SE104-03')).toContainText('Not assigned')
  await expect(rowFor(page, 'SE104-03')).toContainText('Active')
  await page.reload()
  await expect(rowFor(page, 'SE104-03')).toBeVisible()
  await page.goto('/admin')
  await expect(page.locator('.admin-metric').filter({ hasText: 'Active classes' }).locator('strong')).toHaveText('4')
  await expect(page.getByRole('button', { name: 'SE104-03', exact: true })).toBeVisible()
})

