test('stale course and class records, storage errors never report a save', async ({ page }) => {
  await openClasses(page)
  await page.getByRole('button', { name: 'Edit SE104-02', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Class code', { exact: false }).fill('CHANGED')
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Unavailable') } })
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Unable to save')
  await expect(dialog.getByLabel('Class code', { exact: false })).toHaveValue('CHANGED')
  await page.reload()
  await page.getByRole('button', { name: 'Edit SE104-02', exact: true }).click()
  await page.evaluate((key) => sessionStorage.setItem(key, '[]'), courseKey)
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog.locator('#class-courseId-error')).toContainText('no longer available')
  await page.evaluate((key) => sessionStorage.setItem(key, '[]'), classKey)
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog.getByRole('alert')).toContainText('class is no longer available')
})
