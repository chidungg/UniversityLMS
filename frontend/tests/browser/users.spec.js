import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const key = 'university-lms.user-preview.v1'
async function openDirectory(page) {
  await page.goto('/admin/users')
  await expect(page.getByRole('table')).toBeVisible()
}

for (const width of [1024, 1440, 1920]) {
  test(`user directory desktop layout ${width}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    await openDirectory(page)
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.screenshot({ path: testInfo.outputPath(`users-${width}.png`), fullPage: true })
  })
}

test('search, combined filters, sorting, pagination and clear', async ({ page }) => {
  await openDirectory(page)
  await page.getByLabel('Search users').fill('LINH@EXAMPLE')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.locator('tbody')).toContainText('Linh Tran')
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click()
  await page.getByLabel('Role', { exact: true }).selectOption('Student')
  await page.getByLabel('Status', { exact: true }).selectOption('Inactive')
  await expect(page.locator('tbody')).toContainText('Ha Do')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByLabel('Search users').fill('unmatched')
  await expect(page.getByRole('heading', { name: 'No users found' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear all filters' }).click()
  await page.getByLabel('Rows per page').selectOption('5')
  await expect(page.locator('tbody tr')).toHaveCount(5)
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(3)
  await page.getByRole('button', { name: 'Sort by full name' }).click()
  await expect(page.getByRole('columnheader', { name: 'Sort by full name' })).toHaveAttribute('aria-sort', 'descending')
  await expect(page.locator('tbody tr').first()).toContainText('Minh Nguyen')
})

test('create validates, saves once, persists and synchronizes overview', async ({ page }, testInfo) => {
  await openDirectory(page)
  await page.getByRole('button', { name: 'Add user', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(page.getByLabel('Full name', { exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: 'Add user', exact: true }).click()
  await expect(dialog.getByText('Enter a full name.', { exact: true }).last()).toBeVisible()
  await expect(dialog.locator('.user-error-summary')).toBeFocused()
  await page.getByLabel('Full name', { exact: true }).fill('Alex Nguyen')
  await page.getByLabel('Email address', { exact: true }).fill('MINH@example.edu')
  await dialog.getByRole('button', { name: 'Add user', exact: true }).click()
  await expect(dialog.locator('#user-email-error')).toContainText('already in use')
  await page.getByLabel('Email address', { exact: true }).fill('alex@example.edu')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('add-user.png'), fullPage: true })
  await dialog.getByRole('button', { name: 'Add user', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Saving…' })).toBeDisabled()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.user-feedback')).toContainText('Alex Nguyen added')
  await page.reload()
  await expect(page.locator('tbody')).toContainText('alex@example.edu')
  await page.getByRole('navigation', { name: 'Administration', exact: true }).getByRole('link', { name: 'Overview', exact: true }).click()
  await expect(page.locator('.admin-metric').filter({ hasText: 'Student accounts' }).locator('strong')).toHaveText('7')
})

test('edit role, deactivate confirmation, cancel and reactivate', async ({ page }) => {
  await openDirectory(page)
  await page.getByRole('button', { name: 'Edit An Le', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Role', { exact: true }).selectOption('Admin')
  await expect(dialog).toContainText('Changing from Student to Admin')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog).toHaveCount(0)
  const row = page.locator('tbody tr').filter({ has: page.getByRole('cell', { name: 'an@example.edu', exact: true }) })
  await expect(row).toContainText('Admin')
  const trigger = page.getByRole('button', { name: 'Deactivate An Le', exact: true })
  await trigger.click()
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await dialog.getByRole('button', { name: 'Deactivate user', exact: true }).click()
  await expect(row).toContainText('Inactive')
  await page.getByRole('button', { name: 'Activate An Le', exact: true }).click()
  await dialog.getByRole('button', { name: 'Activate user', exact: true }).click()
  await expect(row).toContainText('Active')
})

test('offline load retry and save errors preserve input; discard restores focus', async ({ page, context }) => {
  await openDirectory(page)
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Unable to load users' })).toBeVisible()
  await context.setOffline(false)
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('table')).toBeVisible()
  const trigger = page.getByRole('button', { name: 'Edit An Le', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await page.getByLabel('Full name', { exact: true }).fill('An Updated')
  await context.setOffline(true)
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog.getByRole('alert')).toContainText('You are offline')
  await expect(page.getByLabel('Full name', { exact: true })).toHaveValue('An Updated')
  await context.setOffline(false)
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit An Updated', exact: true }).click()
  await page.getByLabel('Full name', { exact: true }).fill('Discard me')
  await page.keyboard.press('Escape')
  await expect(dialog.getByText('Discard your changes?', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Keep editing' }).click()
  await expect(page.getByLabel('Full name', { exact: true })).toBeFocused()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await dialog.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit An Updated', exact: true })).toBeFocused()
  await expect(page.locator('tbody')).not.toContainText('Discard me')
})

test('empty directory, long data and 100+ users', async ({ page }) => {
  await page.goto('/login')
  await page.evaluate((storageKey) => sessionStorage.setItem(storageKey, '[]'), key)
  await page.goto('/admin/users')
  await expect(page.getByRole('heading', { name: 'No users yet' })).toBeVisible()
  await page.getByRole('button', { name: 'Add your first user' }).click()
  await page.keyboard.press('Escape')
  await page.evaluate((storageKey) => sessionStorage.setItem(storageKey, JSON.stringify(Array.from({ length: 105 }, (_, index) => ({ id: `U${index}`, name: `Alexandra Catherine Nguyen ${'Long name '.repeat(5)}${index}`, email: `${'long'.repeat(25)}${index}@example.edu`, role: 'Student', status: 'Active' })))), key)
  await page.reload()
  await expect(page.locator('tbody tr')).toHaveCount(10)
  await page.setViewportSize({ width: 1024, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.locator('.admin-table-scroll').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await expect(page.getByText('Page 1 of 11', { exact: true })).toBeVisible()
})

test('storage failure and stale record never report success', async ({ page }) => {
  await openDirectory(page)
  await page.getByRole('button', { name: 'Edit An Le', exact: true }).click()
  await page.getByLabel('Full name', { exact: true }).fill('An Updated')
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Unavailable') } })
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('alert')).toContainText('Unable to save')
  await expect(page.getByLabel('Full name', { exact: true })).toHaveValue('An Updated')
  await page.reload()
  await page.getByRole('button', { name: 'Edit An Le', exact: true }).click()
  await page.evaluate((storageKey) => sessionStorage.setItem(storageKey, '[]'), key)
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('alert')).toContainText('no longer available')
})
